# Generates the boilerplate of the zombie port: the fake-object protocol types (types.mn part)
# and the message pairs + getters (zombie.mn part) that make-fake-object-type* generates in Racket.
# usage: zombie_gen.py types|msgs
import sys

TAGS = {'x': 1, 'y': 2, 'posn': 3, 'move-toward/speed': 4, 'move': 5, 'draw-on/image': 6, 'dist': 7,
        'move-toward': 8, 'draw-on': 9, 'draw-on/color': 10, 'touching?': 11, 'dead': 12, 'undead': 13,
        'eat-brains': 14, 'kill-all': 15, 'on-mouse': 16, 'on-tick': 17, 'to-draw': 18, 'stop-when': 19}

# function types: name -> (params, result)
FUNS = {
    'IRealThunk': ([], 'Float'),
    'IPosnThunk': ([], 'IPosn'),
    'IPosnRealToPosn': (['IPosn p', 'Float speed'], 'IPosn'),
    'IRealRealToPosn': (['Float dx', 'Float dy'], 'IPosn'),
    'IImageImageToImage': (['IImage img', 'IImage scn'], 'IImage'),
    'IPosnToReal': (['IPosn p'], 'Float'),
    'IPosnToPlayer': (['IPosn p'], 'IPlayer'),
    'IImageToImage': (['IImage scn'], 'IImage'),
    'IStringImageToImage': (['String c', 'IImage s'], 'IImage'),
    'IPosnToBool': (['IPosn p'], 'Bool'),
    'IPosnToZombie': (['IPosn p'], 'IZombie'),
    'IZombiesThunk': ([], 'IZombies'),
    'IPosnToHorde': (['IPosn p'], 'IHorde'),
    'IHordeThunk': ([], 'IHorde'),
    'IPosnToZombies': (['IPosn p'], 'IZombies'),
    'IZombiesToHorde': (['IZombies dead'], 'IHorde'),
    'IMouseToWorld': (['IMouseArgs a'], 'IWorld'),
    'IWorldThunk': ([], 'IWorld'),
    'IImageThunk': ([], 'IImage'),
    'IBoolThunk': ([], 'Bool'),
}

OBJS = [
    ('Posn', [('x', 'IRealThunk'), ('y', 'IRealThunk'), ('posn', 'IPosnThunk'),
              ('move-toward/speed', 'IPosnRealToPosn'), ('move', 'IRealRealToPosn'),
              ('draw-on/image', 'IImageImageToImage'), ('dist', 'IPosnToReal')]),
    ('Player', [('posn', 'IPosnThunk'), ('move-toward', 'IPosnToPlayer'), ('draw-on', 'IImageToImage')]),
    ('Zombie', [('posn', 'IPosnThunk'), ('draw-on/color', 'IStringImageToImage'),
                ('touching?', 'IPosnToBool'), ('move-toward', 'IPosnToZombie')]),
    ('Horde', [('dead', 'IZombiesThunk'), ('undead', 'IZombiesThunk'), ('draw-on', 'IImageToImage'),
               ('touching?', 'IPosnToBool'), ('move-toward', 'IPosnToHorde'), ('eat-brains', 'IHordeThunk')]),
    ('Zombies', [('move-toward', 'IPosnToZombies'), ('draw-on/color', 'IStringImageToImage'),
                 ('touching?', 'IPosnToBool'), ('kill-all', 'IZombiesToHorde')]),
    ('World', [('on-mouse', 'IMouseToWorld'), ('on-tick', 'IWorldThunk'), ('to-draw', 'IImageThunk'),
               ('stop-when', 'IBoolThunk')]),
]


def camel(s):
    out = ''
    for part in s.replace('?', '').replace('/', '-').split('-'):
        out += part[:1].upper() + part[1:]
    return out


def payloads(fields):
    seen = []
    for _, t in fields:
        if t not in seen:
            seen.append(t)
    return seen


def types():
    o = []
    for name, (params, res) in FUNS.items():
        o.append('interface %s\n{\n\tfun this(%s) : %s;\n}\n\n' % (name, ', '.join(params), res))
    for obj, fields in OBJS:
        tags = ', '.join("'%s = %d" % (f, TAGS[f]) for f, _ in fields)
        o.append('# %s = (-> Symbol (U (Pairof \'msg payload) ...)); messages %s\n' % (obj, tags))
        o.append('interface I%s\n{\n\tfun this(Int msg) : I%sMsg;\n}\n\n' % (obj, obj))
        o.append('# the union of (Pairof \'msg payload) results of an I%s\n' % obj)
        o.append('interface I%sMsg\n{\n\tfun Tag() : Int;\n' % obj)
        for t in payloads(fields):
            o.append('\tfun As%s() : %s;\n' % (t[1:], t))
        o.append('}\n\n')
    return ''.join(o)


def msgs():
    o = []
    for obj, fields in OBJS:
        pls = payloads(fields)
        for t in pls:
            cls = '%sMsg%s' % (obj, t[1:])
            o.append('# (cons tag payload) with a %s payload\n' % t)
            o.append('class %s implements I%sMsg\n{\n' % (cls, obj))
            o.append('\tprivate readonly Int tag;\n\tprivate readonly %s payload;\n' % t)
            o.append('\tpublic constructor(Int t, %s p)\n\t{\n\t\ttag = t;\n\t\tpayload = p;\n\t}\n' % t)
            o.append('\tpublic fun Tag() : Int\n\t{\n\t\treturn tag;\n\t}\n')
            for t2 in pls:
                o.append('\tpublic fun As%s() : %s\n\t{\n' % (t2[1:], t2))
                if t2 == t:
                    o.append('\t\treturn payload;\n')
                else:
                    o.append('\t\tERROR("cdr: wrong payload");\n')
                o.append('\t}\n')
            o.append('}\n\n')
    # getters
    o.append('# the getters generated by make-fake-object-type*\n')
    o.append('class Getters\n{\n')
    for obj, fields in OBJS:
        for f, t in fields:
            g = '%s%s' % (obj, camel(f))
            o.append('\t# %s-%s\n' % (obj.lower(), f))
            o.append('\tpublic static fun %s(I%s v) : %s\n\t{\n' % (g, obj, t))
            o.append('\t\tI%sMsg r = v(%d);\n' % (obj, TAGS[f]))
            o.append('\t\tif (%d == r.Tag())\n\t\t{\n\t\t\treturn r.As%s();\n\t\t}\n' % (TAGS[f], t[1:]))
            o.append('\t\tERROR("%s-%s: type error");\n\t}\n' % (obj.lower(), f))
    o.append('}\n')
    return ''.join(o)


if __name__ == '__main__':
    sys.stdout.write(types() if sys.argv[1] == 'types' else msgs())
