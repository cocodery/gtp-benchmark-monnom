# Pack a list of small integer codes into MonNom static methods that rebuild an ArrayList<Int>.
# usage: packhist.py <codes-file> <ClassName> <bits-per-code> <per-method> [v0,v1,...]
#   codes-file: one integer code per line (0 <= code < 2**bits)
#   optional map: the value stored for each code (default: the code itself)
import sys

codes = [int(l) for l in open(sys.argv[1]) if l.strip()]
cls = sys.argv[2]
bits = int(sys.argv[3])
per = int(sys.argv[4])
mp = [int(x) for x in sys.argv[5].split(',')] if len(sys.argv) > 5 else None
k = 63 // bits
base = 1 << bits

words = []
for i in range(0, len(codes), k):
    w = 0
    for j, c in enumerate(codes[i:i + k]):
        assert 0 <= c < base
        w |= c << (bits * j)
    words.append(w)

o = []
o.append("# generated by packhist.py from the benchmark input: %d codes, %d bits each, %d per word\n" % (len(codes), bits, k))
o.append("class %s\n{\n" % cls)
nch = (len(words) + per - 1) // per
for c in range(nch):
    o.append("\tpublic static fun Words%d(ArrayList<Int> a) : ArrayList<Int>\n\t{\n" % c)
    for w in words[c * per:(c + 1) * per]:
        o.append("\t\ta.Add(%d);\n" % w)
    o.append("\t\treturn a;\n\t}\n")
o.append("\t# value of each code\n\tpublic static fun Map(Int c) : Int\n\t{\n")
if mp:
    for i, v in enumerate(mp):
        if v != i:
            o.append("\t\tif (c == %d)\n\t\t{\n\t\t\treturn %d;\n\t\t}\n" % (i, v))
o.append("\t\treturn c;\n\t}\n")
o.append("\t# unpack the words, one value per element\n")
o.append("\tpublic static fun Load() : ArrayList<Int>\n\t{\n\t\tArrayList<Int> a = new ArrayList<Int>();\n")
for c in range(nch):
    o.append("\t\ta = %s.Words%d(a);\n" % (cls, c))
o.append("\t\tArrayList<Int> res = new ArrayList<Int>();\n")
o.append("\t\tInt total = %d;\n\t\tInt i = 0;\n" % len(codes))
o.append("\t\twhile (i < total)\n\t\t{\n")
o.append("\t\t\tInt w = a.Get(i / %d);\n\t\t\tInt j = i %% %d;\n" % (k, k))
o.append("\t\t\twhile (j > 0)\n\t\t\t{\n\t\t\t\tw = w / %d;\n\t\t\t\tj = j - 1;\n\t\t\t}\n" % base)
o.append("\t\t\tres.Add(%s.Map(w %% %d));\n\t\t\ti = i + 1;\n\t\t}\n\t\treturn res;\n\t}\n" % (cls, base))
o.append("}\n")
sys.stdout.write("".join(o))
