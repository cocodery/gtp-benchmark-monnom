# Generates the data-dependent parts of the zordoz port from the Racket sources and from a dump
# of the parsed .zo file (see zordoz/NOTES.md):
#   zodata.mn  (library: the zo graph), lib-kinds (kind table and predicates, appended to lib.mn),
#   zo-string.mn (zo->spec), zo-transition.mn (zo-transition)
# usage: zordoz_gen.py <zo dump> <zo-string.rkt> <compiler-zo-structs.rkt> <outdir>
import re, sys, json
dump, zstr, zstructs, out = sys.argv[1:5]
st = open(zstructs).read()
kinds = []; fields = {}
def sexps(text):
    text = re.sub(r';[^\n]*', '', text)
    toks = re.findall(r'\(|\)|\[|\]|"(?:[^"\\]|\\.)*"|[^\s()\[\]]+', text)
    def rd(i):
        if toks[i] in '([':
            l = []; i += 1
            while toks[i] not in ')]':
                x, i = rd(i); l.append(x)
            return l, i + 1
        return toks[i], i + 1
    i = 0; res = []
    while i < len(toks):
        x, i = rd(i); res.append(x)
    return res
for e in sexps(st):
    if isinstance(e, list) and e and e[0] == 'define-form-struct':
        h = e[1]
        name, par = (h[0], h[1]) if isinstance(h, list) else (h, 'zo')
        kinds.append((name, par))
        fields[name] = [f[0] for f in e[2]]
kid = {k: i for i, (k, _) in enumerate(kinds)}
parent = dict(kinds)
def allfields(k):
    if k == 'zo': return []
    return allfields(parent[k]) + fields[k]
def subkinds(anc):
    r = []
    for k, _ in kinds:
        x = k
        while x != 'zo':
            if x == anc: r.append(k); break
            x = parent[x]
    return r
def camel(s):
    return ''.join(p.capitalize() for p in re.split(r'[\-=?!]+', s) if p)
def pack(s):
    e = 'Txt.Empty()'
    for i in range(0, len(s), 9):
        v = 0
        for j, ch in enumerate(s[i:i + 9]): v += ord(ch) * 128 ** j
        e = 'Txt.PushWord(%s, %d)' % (e, v)
    return e

# ---- data ----
ints = []
for line in open(dump):
    p = line.split()
    k = kid[p[0]]
    assert int(p[1]) == len(allfields(p[0])), (p[0], p[1], allfields(p[0]))
    ints += [k, int(p[1])] + [int(x) for x in p[2:]]
words = []
for i in range(0, len(ints), 4):
    v = 0
    for j, x in enumerate(ints[i:i + 4]):
        assert 0 <= x < 8192
        v += x * 8192 ** j
    words.append(v)
per = 500
parts = [words[i:i + per] for i in range(0, len(words), per)]
L = ['# The zo graph of base/typed-zo-find_rkt.zo as parsed by base/compiler-zo-parse.rkt (Racket),',
     '# serialized by gtp-benchmarks-monnom/tools/zordoz_gen.py (library file: not devolved).',
     '# Per node, in id order: kind, field count, then each field as a datum:',
     '#   0 id = zo node, 1 = (), 2 car cdr = pair, 3 n e1..en = vector, 4 = #f, 5 = #t,',
     '#   6 = any other value (symbols, numbers, strings, hashes, boxes, non-zo structs, ...).',
     '# %d Ints packed 4 per Int (base 8192, first in the lowest digit).' % len(ints),
     'class ZoData', '{',
     '\tpublic static fun Count() : Int', '\t{', '\t\treturn %d;' % len(ints), '\t}',
     '\tpublic static fun Words() : ArrayList<Int>', '\t{', '\t\tArrayList<Int> w = new ArrayList<Int>();']
L += ['\t\tZoData.Part%d(w);' % k for k in range(len(parts))]
L += ['\t\treturn w;', '\t}']
for k, p in enumerate(parts):
    L += ['\tpublic static fun Part%d(ArrayList<Int> w) : Int' % k, '\t{'] + ['\t\tw.Add(%d);' % v for v in p] + ['\t\treturn 0;', '\t}']
L.append('}')
open(out + '/zodata.mn', 'w').write('\n'.join(L) + '\n')

# ---- kinds ----
K = ['# ---- zo struct kinds (compiler-zo-structs.rkt, generated by tools/zordoz_gen.py) ----', '',
     '# kind ids: ' + ', '.join('%d %s' % (i, k) for i, (k, _) in enumerate(kinds)), 'class Kinds', '{']
for anc in ['form', 'expr', 'binding', 'struct-shape']:
    ks = subkinds(anc)
    K += ['\t# (%s? z)' % anc, '\tpublic static fun Is%s(Int k) : Bool' % camel(anc), '\t{']
    for k in ks:
        K += ['\t\tif (k == %d)' % kid[k], '\t\t{', '\t\t\treturn true;', '\t\t}']
    K += ['\t\treturn false;', '\t}']
K += ['\tpublic static fun Count() : Int', '\t{', '\t\treturn %d;' % len(kinds), '\t}', '}', '']
open(out + '/lib-kinds.mn', 'w').write('\n'.join(K))

def pred(name, var):
    # a Racket predicate on a datum `var`
    if name in ('form', 'expr', 'binding'):
        return 'Zo.Is(%s, Kinds.Is%s(%s.Zo().Kind()))' % (var, camel(name), var) if False else 'Zo.Is%s(%s)' % (camel(name), var)
    return 'Zo.IsKind(%s, %d)' % (var, kid[name])

# ---- specs ----
src = open(zstr).read()
specs = {}
for chunk in re.split(r'\n(?=\(define|\(:)', src):
    m = re.match(r'\(define\s+\(([a-z\-=?!0-9]+)->spec\s+[a-z]+\)', chunk)
    if not m: continue
    t = re.search(r'\(list\s+"([^"]+)"', chunk)
    if t: specs[m.group(1)] = (t.group(1), re.findall(r'\(lcons "([^"]+)"', chunk))
dispatch = ['compilation-top', 'prefix', 'global-bucket', 'module-variable', 'stx'] + \
    ['def-values', 'def-syntaxes', 'seq-for-syntax', 'req', 'seq', 'splice', 'inline-variant', 'mod'] + \
    ['lam', 'closure', 'case-lam', 'let-one', 'let-void', 'install-value', 'let-rec', 'boxenv', 'localref',
     'toplevel', 'topsyntax', 'application', 'branch', 'with-cont-mark', 'beg0', 'varref', 'assign',
     'apply-values', 'with-immed-mark', 'primval'] + \
    ['stx-obj', 'wrap', 'module-shift', 'scope', 'multi-scope'] + \
    ['module-binding', 'decoded-module-binding', 'local-binding', 'free-id=?-binding', 'all-from-module', 'provided']
S = ['# zo-string.rkt: zo->spec (generated by tools/zordoz_gen.py from the Racket source).',
     '# A Spec is the struct name and a list of (field-name . thunk); the benchmark only reads the',
     '# names, the thunks (which format the field values) are never forced.', '', 'class ZoString', '{',
     '\tpublic static fun ZoToSpec(IZo z) : ISpec', '\t{', '\t\tInt k = z.Kind();']
for k in dispatch:
    if k not in specs: continue
    S += ['\t\tif (k == %d)' % kid[k], '\t\t{', '\t\t\treturn ZoString.%sToSpec(z);' % camel(k), '\t\t}']
S += ['\t\tERROR("Cannot format unknown struct");', '\t}']
for k in dispatch:
    if k not in specs: continue
    title, fs = specs[k]
    S += ['\t# (%s->spec z)' % k, '\tpublic static fun %sToSpec(IZo z) : ISpec' % camel(k), '\t{', '\t\tISpecFieldList fs = new SpecFieldNil();']
    for f in reversed(fs):
        S.append('\t\tfs = new SpecFieldCons(Specs.Field(%s, z), fs);' % pack(f))
    S += ['\t\treturn Specs.Make(%s, fs);' % pack(title), '\t}']
S.append('}')
open(out + '/zo-string.mn', 'w').write('\n'.join(S) + '\n')

# ---- transitions ----
ES = 'es'
T = {
 'compilation-top': [('prefix', 'prefix', 'direct'), ('code', 'code', 'match:form')],
 'prefix': [('toplevels', 'toplevels', 'filter:gbmv'), ('stxs', 'stxs', 'filter:true')],
 'stx': [('content', 'content', 'direct')],
 'def-values': [('ids', 'ids', 'filter:toplevel'), ('rhs', 'rhs', 'match:esiv')],
 'def-syntaxes': [('ids', 'ids', 'filter:toplevel'), ('rhs', 'rhs', 'match:es'), ('prefix', 'prefix', 'direct'), ('dummy', 'dummy', 'match:toplevel')],
 'seq-for-syntax': [('forms', 'forms', 'filter:form'), ('prefix', 'prefix', 'direct'), ('dummy', 'dummy', 'match:toplevel')],
 'req': [('reqs', 'reqs', 'direct'), ('dummy', 'dummy', 'direct')],
 'seq': [('forms', 'forms', 'filter:form')],
 'splice': [('forms', 'forms', 'filter:form')],
 'inline-variant': [('direct', 'direct', 'direct'), ('inline', 'inline', 'direct')],
 'mod': [('prefix', 'prefix', 'direct'), ('provides', 'provides', 'special:GetProvided'), ('body', 'body', 'filter:form'),
         ('syntax-bodies', 'syntax-bodies', 'special:GetSyntaxes'), ('dummy', 'dummy', 'direct'),
         ('internal-context', 'internal-context', 'special:InternalContext'), ('pre-submodules', 'pre-submodules', 'direct'),
         ('post-submodules', 'post-submodules', 'direct')],
 'lam': [('body', 'body', 'match:es')],
 'closure': [('code', 'code', 'direct')],
 'case-lam': [('clauses', 'clauses', 'direct')],
 'let-one': [('rhs', 'rhs', 'match:es'), ('body', 'body', 'match:es')],
 'let-void': [('body', 'body', 'match:es')],
 'install-value': [('rhs', 'rhs', 'match:es'), ('body', 'body', 'match:es')],
 'let-rec': [('procs', 'procs', 'direct'), ('body', 'body', 'match:es')],
 'boxenv': [('body', 'body', 'match:es')],
 'application': [('rator', 'rator', 'match:es'), ('rands', 'rands', 'filter:es')],
 'branch': [('test', 'test', 'match:es'), ('then', 'then', 'match:es'), ('else', 'else', 'match:es')],
 'with-cont-mark': [('key', 'key', 'match:es'), ('val', 'val', 'match:es'), ('body', 'body', 'match:es')],
 'beg0': [('seq', 'seq', 'filter:es')],
 'varref': [('toplevel', 'toplevel', 'match:toplevel'), ('dummy', 'dummy', 'match:toplevel')],
 'assign': [('id', 'id', 'direct'), ('rhs', 'rhs', 'match:es')],
 'apply-values': [('proc', 'proc', 'match:es'), ('args-expr', 'args-expr', 'match:es')],
 'with-immed-mark': [('key', 'key', 'match:es'), ('def-val', 'def-val', 'match:es'), ('body', 'body', 'match:es')],
 'stx-obj': [('wrap', 'wrap', 'direct')],
 'wrap': [('shifts', 'shifts', 'direct'), ('simple-scopes', 'simple-scopes', 'direct'), ('multi-scopes', 'multi-scopes', 'special:MapCar')],
 'scope': [('bindings', 'bindings', 'special:GetBindings'), ('bulk-bindings', 'bulk-bindings', 'special:GetBulkBindings'), ('multi-owner', 'multi-owner', 'direct')],
 'multi-scope': [('scopes', 'scopes', 'special:MapCadr')],
 'free-id=?-binding': [('base', 'base', 'direct'), ('id', 'id', 'direct')],
}
P = {'form': 'Zo.IsForm(v)', 'toplevel': 'Zo.IsKind(v, %d)' % kid['toplevel'], 'es': 'Zo.IsExprOrSeq(v)',
     'esiv': 'Zo.IsExprSeqOrInlineVariant(v)', 'gbmv': 'Zo.IsGbOrMv(v)', 'true': 'Zo.IsTrue(v)'}
X = ['# zo-transition.rkt: the children of a zo struct by field name (generated by',
     '# tools/zordoz_gen.py; the table of transitions is transcribed from the Racket source).',
     '# try-transition returns a datum: a zo, a list, or #f.', '', 'class ZoTransition', '{',
     '\tpublic static fun ZoTransition(IZo z, IText fieldName) : ITransResult',
     '\t{',
     '\t\tIDatum nxt = ZoTransition.TryTransition(z, fieldName);',
     '\t\tif (nxt.Kind() == 0)',
     '\t\t{',
     '\t\t\treturn Trans.One(nxt.Zo());',
     '\t\t}',
     '\t\tif (Datums.IsList(nxt))',
     '\t\t{',
     '\t\t\tIZoList zs = Datums.FilterZo(nxt);',
     '\t\t\tif (zs.IsEmpty())',
     '\t\t\t{',
     '\t\t\t\treturn Trans.Fail(z);',
     '\t\t\t}',
     '\t\t\treturn Trans.Many(zs);',
     '\t\t}',
     '\t\treturn Trans.Fail(z);',
     '\t}',
     '\tpublic static fun TryTransition(IZo z, IText str) : IDatum',
     '\t{', '\t\tInt k = z.Kind();']
for k in dispatch:
    X += ['\t\tif (k == %d)' % kid[k], '\t\t{', '\t\t\treturn ZoTransition.%sTo(z, str);' % camel(k), '\t\t}']
X += ['\t\treturn Datums.False();', '\t}']
for k in dispatch:
    X += ['\t# (%s-> z field-name)' % k, '\tpublic static fun %sTo(IZo z, IText fieldName) : IDatum' % camel(k), '\t{']
    for name, acc, op in T.get(k, []):
        idx = allfields(k).index(acc)
        X += ['\t\tif (Txt.Equal(fieldName, %s))' % pack(name), '\t\t{', '\t\t\tIDatum v = z.Field(%d);' % idx]
        if op == 'direct':
            X += ['\t\t\treturn v;']
        elif op.startswith('match:'):
            X += ['\t\t\tif (%s)' % P[op[6:]], '\t\t\t{', '\t\t\t\treturn v;', '\t\t\t}', '\t\t\treturn Datums.False();']
        elif op.startswith('filter:'):
            X += ['\t\t\treturn Datums.Filter%s(v);' % camel(op[7:])]
        else:
            X += ['\t\t\treturn ZoTransition.%s(v);' % op[8:]]
        X += ['\t\t}']
    X += ['\t\treturn Datums.False();', '\t}']
open(out + '/zo-transition.part', 'w').write('\n'.join(X) + '\n')
print([k for k in dispatch if k not in specs]); print(len(kinds), 'kinds', len(ints), 'ints', len(parts), 'parts')
