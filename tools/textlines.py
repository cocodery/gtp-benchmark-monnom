# Embed a text file as a MonNom library class returning ArrayList<ArrayList<Int>> (one list of
# character codes per line, as racket's file->lines). Characters are packed 9 per Int (base 128).
# usage: textlines.py <file> <ClassName> [lines-per-method] [wide]
#   wide: the file is UTF-8 and characters are Unicode code points, 3 per Int (base 2^21)
import sys
path, cls = sys.argv[1], sys.argv[2]
per = int(sys.argv[3]) if len(sys.argv) > 3 else 200
wide = len(sys.argv) > 4 and sys.argv[4] == 'wide'
BITS, K = (21, 3) if wide else (7, 9)
data = open(path, encoding='utf-8' if wide else 'latin-1').read()
lines = data.split('\n')
if lines and lines[-1] == '':
    lines.pop()
lines = [l[:-1] if l.endswith('\r') else l for l in lines]
def pack(chunk):
    v = 0
    for i, ch in enumerate(chunk):
        c = ord(ch)
        assert 0 < c < (1 << BITS), c
        v |= c << (BITS * i)
    return v
o = ["# generated by textlines.py from %s: %d lines\n" % (path.split('/')[-1], len(lines))]
o.append("class %s\n{\n" % cls)
o.append("\tpublic static fun Unpack(ArrayList<Int> words, Int len) : ArrayList<Int>\n\t{\n"
         "\t\tArrayList<Int> t = new ArrayList<Int>();\n"
         "\t\tforeach (Int w in words)\n\t\t{\n"
         "\t\t\tInt k = 0;\n\t\t\twhile (k < %d)\n\t\t\t{\n"
         "\t\t\t\tif (t.Length() < len)\n\t\t\t\t{\n\t\t\t\t\tt.Add(w %% %d);\n\t\t\t\t}\n"
         "\t\t\t\tw = w / %d;\n\t\t\t\tk = k + 1;\n\t\t\t}\n\t\t}\n\t\treturn t;\n\t}\n" % (K, 1 << BITS, 1 << BITS))
nch = (len(lines) + per - 1) // per
for c in range(nch):
    o.append("\tpublic static fun Lines%d(ArrayList<ArrayList<Int>> res) : ArrayList<ArrayList<Int>>\n\t{\n\t\tArrayList<Int> w = new ArrayList<Int>();\n" % c)
    for l in lines[c * per:(c + 1) * per]:
        o.append("\t\tw = new ArrayList<Int>();\n")
        for i in range(0, len(l), K):
            o.append("\t\tw.Add(%d);\n" % pack(l[i:i + K]))
        o.append("\t\tres.Add(%s.Unpack(w, %d));\n" % (cls, len(l)))
    o.append("\t\treturn res;\n\t}\n")
o.append("\tpublic static fun Lines() : ArrayList<ArrayList<Int>>\n\t{\n\t\tArrayList<ArrayList<Int>> res = new ArrayList<ArrayList<Int>>();\n")
for c in range(nch):
    o.append("\t\tres = %s.Lines%d(res);\n" % (cls, c))
o.append("\t\treturn res;\n\t}\n}\n")
sys.stdout.write("".join(o))
